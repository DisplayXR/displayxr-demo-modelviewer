bool ModelRenderer::init(VkInstance instance,
                         VkPhysicalDevice physicalDevice,
                         VkDevice device,
                         VkQueue queue,
                         uint32_t queueFamilyIndex,
                         uint32_t renderWidth,
                         uint32_t renderHeight) {
    instance_ = instance;
    physDevice_ = physicalDevice;
    device_ = device;
    queue_ = queue;
    queueFamily_ = queueFamilyIndex;
    width_ = renderWidth;
    height_ = renderHeight;

    VkCommandPoolCreateInfo poolInfo = {VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO};
    poolInfo.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
    poolInfo.queueFamilyIndex = queueFamilyIndex;
    if (vkCreateCommandPool(device, &poolInfo, nullptr, &cmdPool_) != VK_SUCCESS) {
        std::fprintf(stderr, "ModelRenderer: failed to create command pool\n");
        return false;
    }

    {
        // Issue #75 acceptance probe — see transmissionProbe_. Off unless the
        // env var is explicitly 1, so a stray empty value can't enable it.
        const char* probe = std::getenv("DXR_MODELVIEWER_TRANSMISSION_PROBE");
        transmissionProbe_ = (probe && probe[0] == '1' && probe[1] == '\0');
        if (transmissionProbe_)
            std::printf("ModelRenderer: TRANSMISSION PROBE on — transmissive surfaces "
                        "show their raw scene sample, not shading (issue #75)\n");
    }

    {
        // The scene-linear attachment (issue #75) needs to be a colour
        // attachment, be blit-able both ways (the transmission mip chain is
        // built by successive vkCmdBlitImage) and be linear-filterable when
        // sampled. All four are mandatory for R16G16B16A16_SFLOAT in optimal
        // tiling, so this is a diagnostic, not a fallback — if it ever fires,
        // transmission is what breaks, and silently is the wrong way to find out.
        VkFormatProperties fp{};
        vkGetPhysicalDeviceFormatProperties(physDevice_, sceneLinearFormat_, &fp);
        const VkFormatFeatureFlags need =
            VK_FORMAT_FEATURE_COLOR_ATTACHMENT_BIT | VK_FORMAT_FEATURE_BLIT_SRC_BIT |
            VK_FORMAT_FEATURE_BLIT_DST_BIT | VK_FORMAT_FEATURE_SAMPLED_IMAGE_FILTER_LINEAR_BIT;
        if ((fp.optimalTilingFeatures & need) != need) {
            std::printf("ModelRenderer: WARNING scene-linear format %d lacks features "
                        "0x%x (has 0x%x) — transmission may be wrong\n",
                        (int)sceneLinearFormat_, (unsigned)(need & ~fp.optimalTilingFeatures),
                        (unsigned)fp.optimalTilingFeatures);
        }
    }

    chooseSampleCount();
    if (!createRenderTargets()) return false;
    if (!createPipeline()) return false;
    if (!createSamplerAndDefaults()) return false;
    if (!createIbl()) return false;

    {
        // Set 1 now binds MTEX_COUNT samplers and set 2 binds 5, so the fragment
        // stage wants MTEX_COUNT+5. Vulkan only GUARANTEES 16 per stage; real
        // desktop and mobile GPUs report far more, but a device at the minimum
        // would fail with an opaque pipeline-layout error, so say so up front.
        VkPhysicalDeviceProperties props{};
        vkGetPhysicalDeviceProperties(physDevice_, &props);
        const uint32_t need = (uint32_t)MTEX_COUNT + 5;
        const uint32_t have = props.limits.maxPerStageDescriptorSampledImages;
        if (have < need) {
            std::printf("ModelRenderer: WARNING device allows %u sampled images per stage, "
                        "this pipeline needs %u — material textures may fail to bind\n", have, need);
        } else {
            std::printf("ModelRenderer: sampled images per stage: need %u, device allows %u\n",
                        need, have);
        }
    }

    initialized_ = true;
    std::printf("ModelRenderer: initialized (%ux%u)\n", width_, height_);
    return true;
}

// Pick the rasterisation sample count once, at init.
//
// 4x is the target: it is the level `antialias: true` gets in a browser, it is
// universally supported on desktop, and the step from 4 to 8 buys far less than
// it costs on a renderer that already runs the whole pass once PER VIEW TILE.
// The count has to be supported for the colour format, the scene-linear format
// AND depth - framebufferColorSampleCounts alone is not enough, because the two
// colour attachments have different formats and a device may differ on them.
void ModelRenderer::chooseSampleCount() {
    VkPhysicalDeviceProperties props{};
    vkGetPhysicalDeviceProperties(physDevice_, &props);

    auto supported = [&](VkSampleCountFlagBits want) {
        VkSampleCountFlags common = props.limits.framebufferColorSampleCounts &
                                    props.limits.framebufferDepthSampleCounts;
        if ((common & want) == 0) return false;
        // Per-format check: the limits above are the framebuffer's ceiling, not
        // a promise for a specific format+usage pair.
        const VkFormat fmts[3] = {colorFormat_, sceneLinearFormat_, depthFormat_};
        const VkImageUsageFlags usages[3] = {
            VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT,
            VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT,
            VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT};
        for (int i = 0; i < 3; ++i) {
            VkImageFormatProperties ifp{};
            if (vkGetPhysicalDeviceImageFormatProperties(
                    physDevice_, fmts[i], VK_IMAGE_TYPE_2D, VK_IMAGE_TILING_OPTIMAL,
                    usages[i], 0, &ifp) != VK_SUCCESS)
                return false;
            if ((ifp.sampleCounts & want) == 0) return false;
        }
        return true;
    };

    VkSampleCountFlagBits want = VK_SAMPLE_COUNT_4_BIT;
    // DXR_MODELVIEWER_MSAA=<n> makes the 1-vs-4 comparison runnable without a
    // rebuild, which is what an aliasing claim has to be settled with.
    if (const char* e = std::getenv("DXR_MODELVIEWER_MSAA")) {
        const int n = std::atoi(e);
        want = (n >= 8) ? VK_SAMPLE_COUNT_8_BIT
             : (n >= 4) ? VK_SAMPLE_COUNT_4_BIT
             : (n >= 2) ? VK_SAMPLE_COUNT_2_BIT
                        : VK_SAMPLE_COUNT_1_BIT;
    }

    samples_ = VK_SAMPLE_COUNT_1_BIT;
    if (want != VK_SAMPLE_COUNT_1_BIT) {
        if (supported(want)) {
            samples_ = want;
        } else if (want != VK_SAMPLE_COUNT_4_BIT && supported(VK_SAMPLE_COUNT_4_BIT)) {
            samples_ = VK_SAMPLE_COUNT_4_BIT;
        } else if (supported(VK_SAMPLE_COUNT_2_BIT)) {
            samples_ = VK_SAMPLE_COUNT_2_BIT;
        }
    }
    std::printf("ModelRenderer: MSAA %ux%s\n", (unsigned)samples_,
                (samples_ == want) ? "" : " (requested level unsupported)");
}

bool ModelRenderer::createAttachment(ModelImage& img, uint32_t w, uint32_t h,
                                     VkFormat fmt, VkImageUsageFlags usage,
                                     VkSampleCountFlagBits samples,
                                     VkImageAspectFlags aspect) {
    VkImageCreateInfo ici = {VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
    ici.imageType = VK_IMAGE_TYPE_2D; ici.format = fmt;
    ici.extent = {w, h, 1}; ici.mipLevels = 1; ici.arrayLayers = 1;
    ici.samples = samples; ici.tiling = VK_IMAGE_TILING_OPTIMAL;
    ici.usage = usage; ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    ici.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    if (vkCreateImage(device_, &ici, nullptr, &img.image) != VK_SUCCESS) return false;
    VkMemoryRequirements mr; vkGetImageMemoryRequirements(device_, img.image, &mr);
    VkMemoryAllocateInfo ai = {VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    ai.allocationSize = mr.size;
    ai.memoryTypeIndex = modelFindMemoryType(physDevice_, mr.memoryTypeBits,
                                             VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (vkAllocateMemory(device_, &ai, nullptr, &img.memory) != VK_SUCCESS) return false;
    vkBindImageMemory(device_, img.image, img.memory, 0);
    VkImageViewCreateInfo vci = {VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
    vci.image = img.image; vci.viewType = VK_IMAGE_VIEW_TYPE_2D; vci.format = fmt;
    vci.subresourceRange = {aspect, 0, 1, 0, 1};
    if (vkCreateImageView(device_, &vci, nullptr, &img.view) != VK_SUCCESS) return false;
    img.width = w; img.height = h;
    return true;
}

bool ModelRenderer::createRenderTargets() {
    // Render pass (format-only; size-independent). Clears colour+depth, leaves
    // colour in TRANSFER_SRC for the per-eye viewport blit.
    //
    // Attachment 1 is the scene-linear copy of attachment 0 — same geometry,
    // same pixels, but pre-tone-map and pre-encode. It exists so transmission
    // can sample scene radiance instead of display-referred pixels (issue #75);
    // see sceneLinearImage_. It is written unconditionally rather than only for
    // models that contain glass, because the render pass and the pipelines are
    // built at init while hasTransmissive_ is only known after a model loads
    // (and models are loaded and swapped at runtime via L / drag-drop).
    // MSAA (samples_ > 1) adds two RESOLVE attachments, 3 and 4. Attachments 0
    // and 1 then carry the multisampled twins and the subpass resolves them
    // into colorImage_ / sceneLinearImage_ - which keep the single-sample
    // identity, layout and finalLayout they always had, so nothing downstream
    // (the per-eye blit, captureSceneColor, the mip chain) changes at all.
    const bool msaa = (samples_ != VK_SAMPLE_COUNT_1_BIT);

    VkAttachmentDescription atts[5] = {};
    atts[0].format = colorFormat_;
    atts[0].samples = samples_;
    atts[0].loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
    atts[0].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    atts[0].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
    atts[0].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
    atts[0].initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    // The MSAA image is never transferred from - only resolved - so it stays a
    // colour attachment across both passes; only the resolve target goes to
    // TRANSFER_SRC for the blit.
    atts[0].finalLayout = msaa ? VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL
                               : VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;

    atts[1] = atts[0];
    atts[1].format = sceneLinearFormat_;

    atts[2].format = depthFormat_;
    atts[2].samples = samples_;
    atts[2].loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
    // STORE, not DONT_CARE: the transmissive pass (renderPassLoad_ below) does
    // LOAD_OP_LOAD on this same depth attachment so glass depth-tests against the
    // opaque scene. DONT_CARE makes those contents undefined between the passes —
    // tolerated on drivers that leave depth resident, but on a driver that honours
    // the discard the transmissive draws fail the depth test and vanish entirely.
    atts[2].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    atts[2].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
    atts[2].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
    atts[2].initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    atts[2].finalLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;

    // Resolve targets: single-sample, contents irrelevant on entry (the resolve
    // overwrites every pixel of the render area), TRANSFER_SRC on the way out.
    atts[3].format = colorFormat_;
    atts[3].samples = VK_SAMPLE_COUNT_1_BIT;
    atts[3].loadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
    atts[3].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
    atts[3].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
    atts[3].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
    atts[3].initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    atts[3].finalLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
    atts[4] = atts[3];
    atts[4].format = sceneLinearFormat_;

    VkAttachmentReference colorRefs[2] = {
        {0, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL},
        {1, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL},
    };
    VkAttachmentReference resolveRefs[2] = {
        {3, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL},
        {4, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL},
    };
    VkAttachmentReference depthRef = {2, VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL};
    VkSubpassDescription sub = {};
    sub.pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS;
    sub.colorAttachmentCount = 2;
    sub.pColorAttachments = colorRefs;
    sub.pResolveAttachments = msaa ? resolveRefs : nullptr;
    sub.pDepthStencilAttachment = &depthRef;

    VkSubpassDependency deps[2] = {};
    deps[0].srcSubpass = VK_SUBPASS_EXTERNAL;
    deps[0].dstSubpass = 0;
    deps[0].srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_LATE_FRAGMENT_TESTS_BIT;
    deps[0].dstStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT;
    deps[0].srcAccessMask = 0;
    deps[0].dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT | VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;
    deps[1].srcSubpass = 0;
    deps[1].dstSubpass = VK_SUBPASS_EXTERNAL;
    deps[1].srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;
    deps[1].dstStageMask = VK_PIPELINE_STAGE_TRANSFER_BIT;
    deps[1].srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT;
    deps[1].dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT;

    VkRenderPassCreateInfo rpci = {VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO};
    rpci.attachmentCount = msaa ? 5u : 3u;
    rpci.pAttachments = atts;
    rpci.subpassCount = 1;
    rpci.pSubpasses = &sub;
    rpci.dependencyCount = 2;
    rpci.pDependencies = deps;
    if (vkCreateRenderPass(device_, &rpci, nullptr, &renderPass_) != VK_SUCCESS) return false;

    // The transmissive pass runs after the scene-colour capture, so it must LOAD
    // what the opaque pass wrote rather than clear it, and it starts from
    // COLOR_ATTACHMENT_OPTIMAL (an explicit barrier brings the image back from
    // the TRANSFER_SRC the first pass left it in). Depth is loaded too, so
    // transmissive geometry still depth-tests against the opaque scene.
    atts[0].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    atts[0].initialLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    atts[1].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    atts[1].initialLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    atts[2].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
    atts[2].initialLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
    // The resolve targets are rewritten wholesale by pass 2's resolve, so they
    // still LOAD nothing - but they arrive in COLOR_ATTACHMENT_OPTIMAL, put
    // there by renderEye's explicit barrier off the transmission copy's read.
    atts[3].initialLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    atts[4].initialLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
    // OR, not assign: pass 2 LOADs colour and depth that pass 1 WROTE, so the
    // attachment-write stages have to stay in the dependency alongside the
    // transmission sample's shader read.
    deps[0].srcStageMask |= VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT;
    deps[0].srcAccessMask |= VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT |
                             VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;
    if (vkCreateRenderPass(device_, &rpci, nullptr, &renderPassLoad_) != VK_SUCCESS) return false;

    return ensureTargets(width_, height_);
}

// (Re)create the internal colour+depth targets and framebuffer at w×h, reusing
// renderPass_. Called at init and whenever the per-eye viewport size changes
// (window resize) — a fixed-size framebuffer would make the render pass invalid
// once the window grew, leaving the swapchain unwritten (window goes transparent).
bool ModelRenderer::ensureTargets(uint32_t w, uint32_t h) {
    if (w == 0) w = 1;
    if (h == 0) h = 1;
    if (device_ != VK_NULL_HANDLE) vkDeviceWaitIdle(device_);
    if (framebuffer_ != VK_NULL_HANDLE) { vkDestroyFramebuffer(device_, framebuffer_, nullptr); framebuffer_ = VK_NULL_HANDLE; }
    if (colorImage_.image != VK_NULL_HANDLE) modelDestroyImage(device_, colorImage_);
    if (sceneLinearImage_.image != VK_NULL_HANDLE) modelDestroyImage(device_, sceneLinearImage_);
    if (depthImage_.image != VK_NULL_HANDLE) modelDestroyImage(device_, depthImage_);
    if (colorMsaa_.image != VK_NULL_HANDLE) modelDestroyImage(device_, colorMsaa_);
    if (sceneLinearMsaa_.image != VK_NULL_HANDLE) modelDestroyImage(device_, sceneLinearMsaa_);
    if (transmissionImage_.image != VK_NULL_HANDLE) modelDestroyImage(device_, transmissionImage_);
    width_ = w; height_ = h;

    colorImage_ = modelCreateImage2D(device_, physDevice_, w, h, colorFormat_,
        VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT);
    if (colorImage_.image == VK_NULL_HANDLE) return false;

    // The scene-linear twin. TRANSFER_SRC because captureSceneColor copies THIS
    // (not colorImage_) into the mipped image transmission samples.
    sceneLinearImage_ = modelCreateImage2D(device_, physDevice_, w, h, sceneLinearFormat_,
        VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT);
    if (sceneLinearImage_.image == VK_NULL_HANDLE) return false;

    // Depth follows the colour attachments' sample count - a subpass's depth
    // and colour attachments must agree, so this is not an independent choice.
    if (!createAttachment(depthImage_, w, h, depthFormat_,
                          VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT, samples_,
                          VK_IMAGE_ASPECT_DEPTH_BIT)) return false;

    const bool msaa = (samples_ != VK_SAMPLE_COUNT_1_BIT);
    if (msaa) {
        // The multisampled twins. COLOR_ATTACHMENT only - they are resolved,
        // never sampled or transferred.
        if (!createAttachment(colorMsaa_, w, h, colorFormat_,
                              VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, samples_,
                              VK_IMAGE_ASPECT_COLOR_BIT)) return false;
        if (!createAttachment(sceneLinearMsaa_, w, h, sceneLinearFormat_,
                              VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, samples_,
                              VK_IMAGE_ASPECT_COLOR_BIT)) return false;
    }

    // Attachment order mirrors createRenderTargets(): 0,1 = colour (MSAA twins
    // when multisampling), 2 = depth, 3,4 = the resolve targets.
    VkImageView fbViews[5] = {
        msaa ? colorMsaa_.view       : colorImage_.view,
        msaa ? sceneLinearMsaa_.view : sceneLinearImage_.view,
        depthImage_.view,
        colorImage_.view,
        sceneLinearImage_.view,
    };
    VkFramebufferCreateInfo fbci = {VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO};
    if (!createTransmissionTarget(w, h)) return false;
    fbci.renderPass = renderPass_; fbci.attachmentCount = msaa ? 5u : 3u; fbci.pAttachments = fbViews;
    fbci.width = w; fbci.height = h; fbci.layers = 1;
    if (vkCreateFramebuffer(device_, &fbci, nullptr, &framebuffer_) != VK_SUCCESS) return false;
    return true;
}

// The mipped scene-colour copy transmissive surfaces refract against. Mips give
// roughness-blurred refraction for free (a rough transmissive surface should
// scatter what's behind it), which is the whole reason to build a chain rather
// than a flat copy.
//
// It carries sceneLinearFormat_, not colorFormat_ — it is a copy of
// sceneLinearImage_ (issue #75). That also makes the mip chain correct rather
// than merely plausible: box-filtering display-referred pixels averages in a
// non-linear space, so a blurred refraction of a bright/dark edge came out at
// the wrong mean brightness even before the double tone map is accounted for.
bool ModelRenderer::createTransmissionTarget(uint32_t w, uint32_t h) {
    uint32_t mips = 1;
    for (uint32_t d = std::max(w, h); d > 1; d >>= 1) ++mips;
    transmissionMips_ = mips;

    VkImageCreateInfo ici = {VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
    ici.imageType = VK_IMAGE_TYPE_2D; ici.format = sceneLinearFormat_;
    ici.extent = {w, h, 1}; ici.mipLevels = mips; ici.arrayLayers = 1;
    ici.samples = VK_SAMPLE_COUNT_1_BIT; ici.tiling = VK_IMAGE_TILING_OPTIMAL;
    ici.usage = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT |
                VK_IMAGE_USAGE_SAMPLED_BIT;
    ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    if (vkCreateImage(device_, &ici, nullptr, &transmissionImage_.image) != VK_SUCCESS) return false;
    VkMemoryRequirements mr; vkGetImageMemoryRequirements(device_, transmissionImage_.image, &mr);
    VkMemoryAllocateInfo ai = {VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    ai.allocationSize = mr.size;
    ai.memoryTypeIndex = modelFindMemoryType(physDevice_, mr.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (vkAllocateMemory(device_, &ai, nullptr, &transmissionImage_.memory) != VK_SUCCESS) return false;
    vkBindImageMemory(device_, transmissionImage_.image, transmissionImage_.memory, 0);
    VkImageViewCreateInfo vci = {VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
    vci.image = transmissionImage_.image; vci.viewType = VK_IMAGE_VIEW_TYPE_2D; vci.format = sceneLinearFormat_;
    vci.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, mips, 0, 1};
    if (vkCreateImageView(device_, &vci, nullptr, &transmissionImage_.view) != VK_SUCCESS) return false;
    transmissionImage_.width = w; transmissionImage_.height = h;

    // The set-2 descriptor points at the old image after a resize; repoint it.
    if (iblSet_ != VK_NULL_HANDLE) writeIblSet();
    return true;
}

// Copy the opaque pass's SCENE-LINEAR colour into transmissionImage_ and build
// its mip chain. sceneLinearImage_ arrives in TRANSFER_SRC_OPTIMAL (the first
// render pass's finalLayout) and is left there — the caller barriers it back to
// COLOR_ATTACHMENT_OPTIMAL before the transmissive pass.
//
// Issue #75: this used to copy colorImage_, which the shader had already
// tone-mapped and (on a UNORM swapchain) sRGB-encoded. The transmissive pass
// then composited that display-referred value into a still-linear `color` that
// went through both again — the washed-out glass. The source is now the
// pre-tone-map attachment, so the sample and the surface it is composited into
// are in the same space and the tail of pbr.frag runs exactly once.
void ModelRenderer::captureSceneColor(VkCommandBuffer cmd, uint32_t w, uint32_t h) {
    auto barrier = [&](uint32_t mip, uint32_t count, VkImageLayout oldL, VkImageLayout newL,
                       VkAccessFlags srcA, VkAccessFlags dstA,
                       VkPipelineStageFlags srcS, VkPipelineStageFlags dstS) {
        VkImageMemoryBarrier b = {VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
        b.oldLayout = oldL; b.newLayout = newL;
        b.srcAccessMask = srcA; b.dstAccessMask = dstA;
        b.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED; b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        b.image = transmissionImage_.image;
        b.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, mip, count, 0, 1};
        vkCmdPipelineBarrier(cmd, srcS, dstS, 0, 0, nullptr, 0, nullptr, 1, &b);
    };

    // NOTE: only the viewport sub-rect is copied, so the rest of each mip stays
    // undefined. That is fine because the shader scales its UVs into the same
    // sub-rect (ubo.viewport) — but it is exactly why sampling the full [0,1]
    // range returned uninitialized memory before that scaling existed.
    barrier(0, transmissionMips_, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
            0, VK_ACCESS_TRANSFER_WRITE_BIT,
            VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);

    VkImageCopy cp = {};
    cp.srcSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    cp.dstSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    cp.extent = {w, h, 1};
    vkCmdCopyImage(cmd, sceneLinearImage_.image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
                   transmissionImage_.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &cp);

    int32_t mw = (int32_t)w, mh = (int32_t)h;
    for (uint32_t i = 1; i < transmissionMips_; ++i) {
        barrier(i - 1, 1, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
                VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_TRANSFER_READ_BIT,
                VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
        int32_t nw = mw > 1 ? mw / 2 : 1, nh = mh > 1 ? mh / 2 : 1;
        VkImageBlit bl = {};
        bl.srcSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, i - 1, 0, 1};
        bl.srcOffsets[1] = {mw, mh, 1};
        bl.dstSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, i, 0, 1};
        bl.dstOffsets[1] = {nw, nh, 1};
        vkCmdBlitImage(cmd, transmissionImage_.image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
                       transmissionImage_.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
                       1, &bl, VK_FILTER_LINEAR);
        barrier(i - 1, 1, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
                VK_ACCESS_TRANSFER_READ_BIT, VK_ACCESS_SHADER_READ_BIT,
                VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT);
        mw = nw; mh = nh;
    }
    barrier(transmissionMips_ - 1, 1, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
            VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
            VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT,
            VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT);
}

bool ModelRenderer::createPipeline() {
    // Set-0: binding 0 = the per-frame UBO (vertex + fragment); binding 1 = the
    // per-material KHR_materials_* factor SSBO (fragment), indexed by the
    // material id in the push block. See MaterialExtGpu for why it isn't a push
    // constant.
    VkDescriptorSetLayoutBinding b0[2] = {};
    b0[0].binding = 0;
    b0[0].descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER;
    b0[0].descriptorCount = 1;
    b0[0].stageFlags = VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT;
    b0[1].binding = 1;
    b0[1].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    b0[1].descriptorCount = 1;
    b0[1].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
    VkDescriptorSetLayoutCreateInfo dlci = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
    dlci.bindingCount = 2;
    dlci.pBindings = b0;
    if (vkCreateDescriptorSetLayout(device_, &dlci, nullptr, &dsLayout_) != VK_SUCCESS) return false;

    // Set 1: per-material textures — base color, MR, normal, occlusion, emissive.
    VkDescriptorSetLayoutBinding mb[MTEX_COUNT] = {};
    for (uint32_t i = 0; i < MTEX_COUNT; ++i) {
        mb[i].binding = i;
        mb[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        mb[i].descriptorCount = 1;
        mb[i].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
    }
    VkDescriptorSetLayoutCreateInfo mlci = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
    mlci.bindingCount = MTEX_COUNT;
    mlci.pBindings = mb;
    if (vkCreateDescriptorSetLayout(device_, &mlci, nullptr, &matSetLayout_) != VK_SUCCESS) return false;

    // Set 2: IBL — irradiance cube, prefiltered cube, BRDF LUT, plus the mipped
    // scene-colour copy transmissive surfaces refract against (all fragment).
    VkDescriptorSetLayoutBinding ib[5] = {};
    for (uint32_t i = 0; i < 5; ++i) {
        ib[i].binding = i;
        ib[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        ib[i].descriptorCount = 1;
        ib[i].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
    }
    VkDescriptorSetLayoutCreateInfo ilci = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
    ilci.bindingCount = 5;
    ilci.pBindings = ib;
    if (vkCreateDescriptorSetLayout(device_, &ilci, nullptr, &iblSetLayout_) != VK_SUCCESS) return false;

    // Set 3: joint-matrix SSBO for skinning (vertex stage). Always present (a
    // 1-matrix dummy for static models) so the binding is valid every draw.
    VkDescriptorSetLayoutBinding jb = {};
    jb.binding = 0;
    jb.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    jb.descriptorCount = 1;
    jb.stageFlags = VK_SHADER_STAGE_VERTEX_BIT;
    VkDescriptorSetLayoutCreateInfo jlci = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
    jlci.bindingCount = 1;
    jlci.pBindings = &jb;
    if (vkCreateDescriptorSetLayout(device_, &jlci, nullptr, &jointSetLayout_) != VK_SUCCESS) return false;

    VkPushConstantRange pcr = {};
    pcr.stageFlags = VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT;
    pcr.offset = 0;
    pcr.size = sizeof(PushBlock);
    VkDescriptorSetLayout setLayouts[4] = {dsLayout_, matSetLayout_, iblSetLayout_, jointSetLayout_};
    VkPipelineLayoutCreateInfo plci = {VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO};
    plci.setLayoutCount = 4;
    plci.pSetLayouts = setLayouts;
    plci.pushConstantRangeCount = 1;
    plci.pPushConstantRanges = &pcr;
    if (vkCreatePipelineLayout(device_, &plci, nullptr, &pipelineLayout_) != VK_SUCCESS) return false;

    VkShaderModule vs = createShaderModule(device_, pbr_vert_data, sizeof(pbr_vert_data));
    VkShaderModule fs = createShaderModule(device_, pbr_frag_data, sizeof(pbr_frag_data));
    if (vs == VK_NULL_HANDLE || fs == VK_NULL_HANDLE) return false;

    VkPipelineShaderStageCreateInfo stages[2] = {};
    stages[0].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
    stages[0].module = vs;
    stages[0].pName = "main";
    stages[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
    stages[1].module = fs;
    stages[1].pName = "main";

    VkVertexInputBindingDescription vib = {0, sizeof(ModelVertex), VK_VERTEX_INPUT_RATE_VERTEX};
    VkVertexInputAttributeDescription via[6] = {
        {0, 0, VK_FORMAT_R32G32B32_SFLOAT,    (uint32_t)offsetof(ModelVertex, pos)},
        {1, 0, VK_FORMAT_R32G32B32_SFLOAT,    (uint32_t)offsetof(ModelVertex, normal)},
        {2, 0, VK_FORMAT_R32G32_SFLOAT,       (uint32_t)offsetof(ModelVertex, uv)},
        {3, 0, VK_FORMAT_R16G16B16A16_UINT,   (uint32_t)offsetof(ModelVertex, joints0)},
        {4, 0, VK_FORMAT_R32G32B32A32_SFLOAT, (uint32_t)offsetof(ModelVertex, weights0)},
        {5, 0, VK_FORMAT_R32G32B32A32_SFLOAT, (uint32_t)offsetof(ModelVertex, tangent)},
    };
    VkPipelineVertexInputStateCreateInfo vi = {VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO};
    vi.vertexBindingDescriptionCount = 1;
    vi.pVertexBindingDescriptions = &vib;
    vi.vertexAttributeDescriptionCount = 6;
    vi.pVertexAttributeDescriptions = via;

    VkPipelineInputAssemblyStateCreateInfo ia = {VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO};
    ia.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

    VkPipelineViewportStateCreateInfo vp = {VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO};
    vp.viewportCount = 1;
    vp.scissorCount = 1;

    VkPipelineRasterizationStateCreateInfo rs = {VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO};
    rs.polygonMode = VK_POLYGON_MODE_FILL;
    rs.cullMode = VK_CULL_MODE_NONE;       // two-sided shading handles back faces
    // Front-face winding is PER-PLATFORM, and both sides are empirical.
    //
    // The #87 analysis (unconditional CLOCKWISE, v0.21.1) held on macOS: under
    // MoltenVK the negative-height viewport in renderEye reverses facing, every
    // visible fragment reported gl_FrontFacing == false with CCW, and pbr.frag's
    // two-sided flip inverted the normal on all of them — dot(N,V) measured
    // -0.983 head-on where it must be +1, Fresnel pinned near f90, materials
    // rendered as environment mirrors (blue gold, black clearcoat). CLOCKWISE
    // fixed it there, verified by probe (dot(N,V) +0.987) and by eye.
    //
    // On WINDOWS (native Vulkan, NVIDIA) the SAME change inverted the normals
    // instead: v0.20.1 and v0.21.0 render sample.glb's materials correctly with
    // COUNTER_CLOCKWISE, and v0.21.1 — whose only functional change was this
    // constant — renders every material as a sky mirror. Reproduced 2026-08-13
    // on one box with the runtime held constant, deterministic captures,
    // releases bisected: 0.20.1 OK, 0.21.0 OK (pixel-identical), 0.21.1 chrome,
    // 0.22.0 chrome. Rejected on the panel by David.
    //
    // So the effective facing parity of the chain (rig view + GL-style
    // projection + negative-height viewport) DIFFERS between MoltenVK and
    // native Vulkan here. Which stack deviates from the VK spec's
    // framebuffer-space rule — and why — is deliberately left open (#92): this
    // constant follows the measurement on each platform, not the theory.
    // Linux/Android ship the native-Vulkan value; on-hardware verification of
    // those two is part of #92.
    //
    // cullMode is NONE, so this changes gl_FrontFacing ONLY — nothing is culled
    // either way, and genuine back faces still get their normal flipped, which
    // is what the two-sided path is for.
#ifdef __APPLE__
    rs.frontFace = VK_FRONT_FACE_CLOCKWISE;          // MoltenVK — measured (#87)
#else
    rs.frontFace = VK_FRONT_FACE_COUNTER_CLOCKWISE;  // native VK — measured (#92)
#endif
    rs.lineWidth = 1.0f;

    // Must equal the render pass's attachment sample count. `ms` is shared with
    // the skybox pipeline built at the end of this function, so both move
    // together - a mismatch on either is a pipeline-creation failure, not a
    // visual artefact.
    VkPipelineMultisampleStateCreateInfo ms = {VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO};
    ms.rasterizationSamples = samples_;

    VkPipelineDepthStencilStateCreateInfo ds = {VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO};
    ds.depthTestEnable = VK_TRUE;
    ds.depthWriteEnable = VK_TRUE;
    ds.depthCompareOp = VK_COMPARE_OP_LESS;

    // Two colour attachments: 0 = display-referred output, 1 = the scene-linear
    // twin transmission samples (issue #75). Same state for both — no blending,
    // full write mask. The count MUST match the subpass's colorAttachmentCount.
    VkPipelineColorBlendAttachmentState cba[2] = {};
    for (VkPipelineColorBlendAttachmentState& a : cba) {
        a.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT |
                           VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
        a.blendEnable = VK_FALSE;
    }
    VkPipelineColorBlendStateCreateInfo cb = {VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO};
    cb.attachmentCount = 2;
    cb.pAttachments = cba;

    VkDynamicState dynStates[2] = {VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR};
    VkPipelineDynamicStateCreateInfo dyn = {VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO};
    dyn.dynamicStateCount = 2;
    dyn.pDynamicStates = dynStates;

    VkGraphicsPipelineCreateInfo gpci = {VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO};
    gpci.stageCount = 2;
    gpci.pStages = stages;
    gpci.pVertexInputState = &vi;
    gpci.pInputAssemblyState = &ia;
    gpci.pViewportState = &vp;
    gpci.pRasterizationState = &rs;
    gpci.pMultisampleState = &ms;
    gpci.pDepthStencilState = &ds;
    gpci.pColorBlendState = &cb;
    gpci.pDynamicState = &dyn;
    gpci.layout = pipelineLayout_;
    gpci.renderPass = renderPass_;
    gpci.subpass = 0;
    VkResult pr = vkCreateGraphicsPipelines(device_, VK_NULL_HANDLE, 1, &gpci, nullptr, &pipeline_);

    vkDestroyShaderModule(device_, vs, nullptr);
    vkDestroyShaderModule(device_, fs, nullptr);
    if (pr != VK_SUCCESS) {
        std::fprintf(stderr, "ModelRenderer: failed to create pipeline (%d)\n", pr);
        return false;
    }

    // Skybox pipeline: fullscreen.vert + skybox.frag, no vertex input, depth
    // test/write off (drawn behind the model). Reuses pipelineLayout_/renderPass_.
    {
        VkShaderModule svs = createShaderModule(device_, fullscreen_vert_data, sizeof(fullscreen_vert_data));
        VkShaderModule sfs = createShaderModule(device_, skybox_frag_data, sizeof(skybox_frag_data));
        VkPipelineShaderStageCreateInfo st2[2] = {};
        st2[0].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO; st2[0].stage = VK_SHADER_STAGE_VERTEX_BIT;   st2[0].module = svs; st2[0].pName = "main";
        st2[1].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO; st2[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT; st2[1].module = sfs; st2[1].pName = "main";
        VkPipelineVertexInputStateCreateInfo vi2 = {VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO};
        VkPipelineDepthStencilStateCreateInfo ds2 = {VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO};
        ds2.depthTestEnable = VK_FALSE; ds2.depthWriteEnable = VK_FALSE;
        VkGraphicsPipelineCreateInfo gp2 = gpci;   // reuse ia/vp/rs/ms/cb/dyn/layout/renderPass
        gp2.pStages = st2;
        gp2.pVertexInputState = &vi2;
        gp2.pDepthStencilState = &ds2;
        VkResult spr = vkCreateGraphicsPipelines(device_, VK_NULL_HANDLE, 1, &gp2, nullptr, &skyboxPipeline_);
        vkDestroyShaderModule(device_, svs, nullptr);
        vkDestroyShaderModule(device_, sfs, nullptr);
        if (spr != VK_SUCCESS) { std::fprintf(stderr, "ModelRenderer: failed to create skybox pipeline (%d)\n", spr); return false; }
    }

    // Descriptor pool + set + the host-visible uniform buffer.
    VkDescriptorPoolSize ps[2] = {{VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, 1},
                                  {VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1}};
    VkDescriptorPoolCreateInfo dpci = {VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
    dpci.maxSets = 1;
    dpci.poolSizeCount = 2;
    dpci.pPoolSizes = ps;
    if (vkCreateDescriptorPool(device_, &dpci, nullptr, &descriptorPool_) != VK_SUCCESS) return false;

    VkDescriptorSetAllocateInfo dsai = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    dsai.descriptorPool = descriptorPool_;
    dsai.descriptorSetCount = 1;
    dsai.pSetLayouts = &dsLayout_;
    if (vkAllocateDescriptorSets(device_, &dsai, &descriptorSet_) != VK_SUCCESS) return false;

    uniformBuffer_ = modelCreateBuffer(device_, physDevice_, sizeof(UniformBlock),
        VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    if (uniformBuffer_.buffer == VK_NULL_HANDLE) return false;

    VkDescriptorBufferInfo dbi = {uniformBuffer_.buffer, 0, sizeof(UniformBlock)};
    VkWriteDescriptorSet w = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
    w.dstSet = descriptorSet_;
    w.dstBinding = 0;
    w.descriptorCount = 1;
    w.descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER;
    w.pBufferInfo = &dbi;
    vkUpdateDescriptorSets(device_, 1, &w, 0, nullptr);

    // Seed binding 1 with a single all-default entry. A model may load before
    // any material extensions exist (or have no materials at all), and the
    // descriptor must reference a live buffer on the very first draw either way.
    if (!uploadMaterialExtensions({})) return false;
    return true;
}

// Pack the loaded materials' KHR_materials_* factors into the set-0 SSBO and
// point the descriptor at it. Called on every model load; the buffer is
// reallocated because material counts vary wildly between assets (1 for a cube,
// 63 for the phase 1 material grid).
bool ModelRenderer::uploadMaterialExtensions(const std::vector<ModelMaterial>& mats) {
    std::vector<MaterialExtGpu> gpu;
    gpu.reserve(mats.empty() ? 1 : mats.size());
    for (const ModelMaterial& m : mats) {
        MaterialExtGpu g{};
        g.p0[0] = m.ior;
        g.p0[1] = m.specularFactor;
        g.p0[2] = m.clearcoatFactor;
        g.p0[3] = m.clearcoatRoughness;
        g.p1[0] = m.specularColorFactor[0];
        g.p1[1] = m.specularColorFactor[1];
        g.p1[2] = m.specularColorFactor[2];
        g.p1[3] = m.sheenRoughness;
        g.p2[0] = m.sheenColorFactor[0];
        g.p2[1] = m.sheenColorFactor[1];
        g.p2[2] = m.sheenColorFactor[2];
        g.p2[3] = m.emissiveStrength;
        g.p3[0] = m.anisotropyStrength;
        g.p3[1] = m.anisotropyRotation;
        g.p3[2] = m.iridescenceFactor;
        g.p3[3] = m.iridescenceIor;
        g.p4[0] = m.iridescenceThicknessMin;
        g.p4[1] = m.iridescenceThicknessMax;
        g.p4[2] = m.transmissionFactor;
        g.p4[3] = m.volumeThickness;
        g.p5[0] = m.attenuationColor[0];
        g.p5[1] = m.attenuationColor[1];
        g.p5[2] = m.attenuationColor[2];
        g.p5[3] = m.attenuationDistance;
        g.p6[0] = m.scatterStrength;
        g.p6[1] = m.scatterAnisotropy;
        g.p6[2] = m.diffuseRoughness;   // KHR_materials_diffuse_roughness
        g.p6[3] = m.fuzzFactor;         // KHR_materials_fuzz (colour/roughness
                                        // ride the sheen lanes — see p7[3])
        g.p7[0] = m.multiscatterColor[0];
        g.p7[1] = m.multiscatterColor[1];
        g.p7[2] = m.multiscatterColor[2];
        // KHR_materials_coat. Written for EVERY material, not only coated ones:
        // the shader's one lobe serves clearcoat too, so coatIor has to carry
        // 1.5 (f0 0.04, the constant the lobe used to hardcode) even where no
        // coat extension exists. hasCoat, not the presence of a lane, is what
        // gates the properties coat adds.
        g.p8[0] = m.coatIor;
        g.p8[1] = m.coatDarkening;
        g.p8[2] = m.coatAnisotropyStrength;
        g.p8[3] = m.coatAnisotropyRotation;
        g.p9[0] = m.coatColor[0];
        g.p9[1] = m.coatColor[1];
        g.p9[2] = m.coatColor[2];
        g.p9[3] = m.hasCoat ? 1.0f : 0.0f;
        g.p7[3] = m.hasFuzz ? 1.0f : 0.0f;
        for (int t = 0; t < (int)MTEX_COUNT; ++t) {
            g.uvXf[t][0] = m.uvXf[t].offset[0];
            g.uvXf[t][1] = m.uvXf[t].offset[1];
            g.uvXf[t][2] = m.uvXf[t].scale[0];
            g.uvXf[t][3] = m.uvXf[t].scale[1];
            g.uvRot[t][0] = m.uvXf[t].rotation;
        }
        gpu.push_back(g);
    }
    if (gpu.empty()) {
        // Defaults matching ModelMaterial's: ior 1.5, specular on, no coat, no
        // sheen, emissive strength 1 — i.e. "behaves as if no extension exists".
        MaterialExtGpu g{};
        g.p0[0] = 1.5f; g.p0[1] = 1.0f;
        g.p1[0] = g.p1[1] = g.p1[2] = 1.0f;
        g.p2[3] = 1.0f;
        g.p3[3] = 1.3f;                    // iridescenceIor
        g.p4[0] = 100.0f; g.p4[1] = 400.0f; // thickness min/max (nm)
        g.p5[0] = g.p5[1] = g.p5[2] = 1.0f; // attenuationColor
        g.p7[0] = g.p7[1] = g.p7[2] = 1.0f; // multiscatterColor (scatterStrength 0 = off)
        g.p8[0] = 1.5f;                     // coatIor -> f0 0.04 (darkening 0, hasCoat 0)
        g.p9[0] = g.p9[1] = g.p9[2] = 1.0f; // coatColor (white = no tint)
        for (int t = 0; t < (int)MTEX_COUNT; ++t) { g.uvXf[t][2] = 1.0f; g.uvXf[t][3] = 1.0f; }
        gpu.push_back(g);
    }

    if (materialExtBuffer_.buffer != VK_NULL_HANDLE) {
        vkQueueWaitIdle(queue_);
        modelDestroyBuffer(device_, materialExtBuffer_);
    }
    const VkDeviceSize bytes = (VkDeviceSize)gpu.size() * sizeof(MaterialExtGpu);
    materialExtBuffer_ = modelCreateBuffer(device_, physDevice_, bytes,
        VK_BUFFER_USAGE_STORAGE_BUFFER_BIT,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    if (materialExtBuffer_.buffer == VK_NULL_HANDLE) return false;
    void* mapped = nullptr;
    vkMapMemory(device_, materialExtBuffer_.memory, 0, bytes, 0, &mapped);
    std::memcpy(mapped, gpu.data(), (size_t)bytes);
    vkUnmapMemory(device_, materialExtBuffer_.memory);
    materialExtCount_ = (uint32_t)gpu.size();

    VkDescriptorBufferInfo bi = {materialExtBuffer_.buffer, 0, bytes};
    VkWriteDescriptorSet w = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
    w.dstSet = descriptorSet_;
    w.dstBinding = 1;
    w.descriptorCount = 1;
    w.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    w.pBufferInfo = &bi;
    vkUpdateDescriptorSets(device_, 1, &w, 0, nullptr);
    return true;
}

ModelImage ModelRenderer::uploadTexture(const ModelTexture& tex) {
    ModelImage img;
    if (tex.width <= 0 || tex.height <= 0 || tex.rgba.empty()) return img;
    img.width = tex.width;
    img.height = tex.height;
    const uint32_t w = (uint32_t)tex.width, h = (uint32_t)tex.height;
    const uint32_t mips = (uint32_t)std::floor(std::log2((float)std::max(w, h))) + 1u;

    VkImageCreateInfo ici = {VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
    ici.imageType = VK_IMAGE_TYPE_2D;
    ici.format = VK_FORMAT_R8G8B8A8_UNORM;  // sRGB decode done in the shader
    ici.extent = {w, h, 1};
    ici.mipLevels = mips;
    ici.arrayLayers = 1;
    ici.samples = VK_SAMPLE_COUNT_1_BIT;
    ici.tiling = VK_IMAGE_TILING_OPTIMAL;
    ici.usage = VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT |
                VK_IMAGE_USAGE_TRANSFER_SRC_BIT;  // SRC for mip blits
    ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    if (vkCreateImage(device_, &ici, nullptr, &img.image) != VK_SUCCESS) return ModelImage{};

    VkMemoryRequirements mr;
    vkGetImageMemoryRequirements(device_, img.image, &mr);
    VkMemoryAllocateInfo ai = {VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    ai.allocationSize = mr.size;
    ai.memoryTypeIndex = modelFindMemoryType(physDevice_, mr.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (vkAllocateMemory(device_, &ai, nullptr, &img.memory) != VK_SUCCESS) { vkDestroyImage(device_, img.image, nullptr); return ModelImage{}; }
    vkBindImageMemory(device_, img.image, img.memory, 0);

    VkImageViewCreateInfo vci = {VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
    vci.image = img.image;
    vci.viewType = VK_IMAGE_VIEW_TYPE_2D;
    vci.format = ici.format;
    vci.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, mips, 0, 1};
    vkCreateImageView(device_, &vci, nullptr, &img.view);

    // Staging upload of mip 0.
    ModelBuffer staging = modelCreateBuffer(device_, physDevice_, tex.rgba.size(),
        VK_BUFFER_USAGE_TRANSFER_SRC_BIT,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    void* mapped = nullptr;
    vkMapMemory(device_, staging.memory, 0, tex.rgba.size(), 0, &mapped);
    std::memcpy(mapped, tex.rgba.data(), tex.rgba.size());
    vkUnmapMemory(device_, staging.memory);

    VkCommandBufferAllocateInfo cbai = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
    cbai.commandPool = cmdPool_; cbai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY; cbai.commandBufferCount = 1;
    VkCommandBuffer cmd; vkAllocateCommandBuffers(device_, &cbai, &cmd);
    VkCommandBufferBeginInfo bi = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(cmd, &bi);

    auto barrier = [&](uint32_t mip, uint32_t count, VkImageLayout oldL, VkImageLayout newL,
                       VkAccessFlags srcA, VkAccessFlags dstA, VkPipelineStageFlags srcS, VkPipelineStageFlags dstS) {
        VkImageMemoryBarrier b = {VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
        b.oldLayout = oldL; b.newLayout = newL;
        b.srcAccessMask = srcA; b.dstAccessMask = dstA;
        b.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED; b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        b.image = img.image;
        b.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, mip, count, 0, 1};
        vkCmdPipelineBarrier(cmd, srcS, dstS, 0, 0, nullptr, 0, nullptr, 1, &b);
    };

    // mip 0 → TRANSFER_DST, copy.
    barrier(0, 1, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
            0, VK_ACCESS_TRANSFER_WRITE_BIT, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
    VkBufferImageCopy region = {};
    region.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    region.imageExtent = {w, h, 1};
    vkCmdCopyBufferToImage(cmd, staging.buffer, img.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);

    // Generate mips by successive blits.
    int32_t mw = (int32_t)w, mh = (int32_t)h;
    for (uint32_t i = 1; i < mips; ++i) {
        // src mip (i-1): TRANSFER_DST → TRANSFER_SRC
        barrier(i - 1, 1, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
                VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_TRANSFER_READ_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
        // dst mip (i): UNDEFINED → TRANSFER_DST
        barrier(i, 1, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
                0, VK_ACCESS_TRANSFER_WRITE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
        int32_t nw = mw > 1 ? mw / 2 : 1, nh = mh > 1 ? mh / 2 : 1;
        VkImageBlit blit = {};
        blit.srcSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, i - 1, 0, 1};
        blit.srcOffsets[1] = {mw, mh, 1};
        blit.dstSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, i, 0, 1};
        blit.dstOffsets[1] = {nw, nh, 1};
        vkCmdBlitImage(cmd, img.image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
                       img.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &blit, VK_FILTER_LINEAR);
        // src mip (i-1) → SHADER_READ
        barrier(i - 1, 1, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
                VK_ACCESS_TRANSFER_READ_BIT, VK_ACCESS_SHADER_READ_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT);
        mw = nw; mh = nh;
    }
    // last mip → SHADER_READ
    barrier(mips - 1, 1, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
            VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT);

    vkEndCommandBuffer(cmd);
    VkSubmitInfo si = {VK_STRUCTURE_TYPE_SUBMIT_INFO};
    si.commandBufferCount = 1; si.pCommandBuffers = &cmd;
    vkQueueSubmit(queue_, 1, &si, VK_NULL_HANDLE);
    vkQueueWaitIdle(queue_);
    vkFreeCommandBuffers(device_, cmdPool_, 1, &cmd);
    modelDestroyBuffer(device_, staging);
    return img;
}

bool ModelRenderer::createSamplerAndDefaults() {
    VkSamplerCreateInfo sci = {VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO};
    sci.magFilter = VK_FILTER_LINEAR;
    sci.minFilter = VK_FILTER_LINEAR;
    sci.mipmapMode = VK_SAMPLER_MIPMAP_MODE_LINEAR;
    sci.addressModeU = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sci.addressModeV = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sci.addressModeW = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sci.maxLod = VK_LOD_CLAMP_NONE;
    sci.borderColor = VK_BORDER_COLOR_FLOAT_OPAQUE_WHITE;
    if (vkCreateSampler(device_, &sci, nullptr, &sampler_) != VK_SUCCESS) return false;

    ModelTexture white; white.width = 1; white.height = 1; white.rgba = {255, 255, 255, 255};
    whiteTex_ = uploadTexture(white);
    ModelTexture flat;  flat.width = 1;  flat.height = 1;  flat.rgba = {128, 128, 255, 255};
    flatNormalTex_ = uploadTexture(flat);
    // KHR_materials_coat's coatAnisotropyTexture is the one slot for which white
    // is NOT the identity. Its RG is a direction VECTOR biased into [0,1] (0.5 =
    // zero), and only B is a multiplier — so white decodes to the direction
    // (1,1), i.e. a spurious 45-degree rotation of the highlight on every
    // material that has no such texture. The neutral is (255, 128, 255):
    // direction (+1, 0) => rotation 0, strength multiplier 1.
    ModelTexture aniso; aniso.width = 1; aniso.height = 1; aniso.rgba = {255, 128, 255, 255};
    coatAnisoDefaultTex_ = uploadTexture(aniso);
    return whiteTex_.view != VK_NULL_HANDLE && flatNormalTex_.view != VK_NULL_HANDLE
        && coatAnisoDefaultTex_.view != VK_NULL_HANDLE;
}

bool ModelRenderer::genCubeMap(CubeMap& cube, uint32_t size, uint32_t mips,
                               const uint32_t* fragSpv, size_t fragSpvBytes, bool /*perMipRoughness*/) {
    cube.size = size; cube.mips = mips;
    const VkFormat fmt = VK_FORMAT_R16G16B16A16_SFLOAT;

    VkImageCreateInfo ici = {VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
    ici.flags = VK_IMAGE_CREATE_CUBE_COMPATIBLE_BIT;
    ici.imageType = VK_IMAGE_TYPE_2D;
    ici.format = fmt;
    ici.extent = {size, size, 1};
    ici.mipLevels = mips;
    ici.arrayLayers = 6;
    ici.samples = VK_SAMPLE_COUNT_1_BIT;
    ici.tiling = VK_IMAGE_TILING_OPTIMAL;
    ici.usage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;
    ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    if (vkCreateImage(device_, &ici, nullptr, &cube.image) != VK_SUCCESS) return false;
    VkMemoryRequirements mreq; vkGetImageMemoryRequirements(device_, cube.image, &mreq);
    VkMemoryAllocateInfo ai = {VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    ai.allocationSize = mreq.size;
    ai.memoryTypeIndex = modelFindMemoryType(physDevice_, mreq.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (vkAllocateMemory(device_, &ai, nullptr, &cube.memory) != VK_SUCCESS) return false;
    vkBindImageMemory(device_, cube.image, cube.memory, 0);

    VkImageViewCreateInfo cvci = {VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
    cvci.image = cube.image; cvci.viewType = VK_IMAGE_VIEW_TYPE_CUBE; cvci.format = fmt;
    cvci.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, mips, 0, 6};
    if (vkCreateImageView(device_, &cvci, nullptr, &cube.view) != VK_SUCCESS) return false;

    // Must match the P block in irradiance.frag / prefilter.frag.
    struct Push { int32_t face; float roughness; float envIsHdri; float envIsRoom; };
    FsPipe fp = makeFsPipe(device_, fmt, fragSpv, fragSpvBytes, sizeof(Push), envSetLayout_);

    for (uint32_t m = 0; m < mips; ++m) {
        uint32_t ms = size >> m; if (ms == 0) ms = 1;
        float rough = (mips > 1) ? (float)m / (float)(mips - 1) : 0.0f;
        for (uint32_t f = 0; f < 6; ++f) {
            VkImageView faceView;
            VkImageViewCreateInfo fv = {VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
            fv.image = cube.image; fv.viewType = VK_IMAGE_VIEW_TYPE_2D; fv.format = fmt;
            fv.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, m, 1, f, 1};
            vkCreateImageView(device_, &fv, nullptr, &faceView);

            VkFramebufferCreateInfo fbci = {VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO};
            fbci.renderPass = fp.rp; fbci.attachmentCount = 1; fbci.pAttachments = &faceView;
            fbci.width = ms; fbci.height = ms; fbci.layers = 1;
            VkFramebuffer fb; vkCreateFramebuffer(device_, &fbci, nullptr, &fb);

            VkCommandBufferAllocateInfo cai = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
            cai.commandPool = cmdPool_; cai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY; cai.commandBufferCount = 1;
            VkCommandBuffer cmd; vkAllocateCommandBuffers(device_, &cai, &cmd);
            VkCommandBufferBeginInfo bi = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
            bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
            vkBeginCommandBuffer(cmd, &bi);
            VkRenderPassBeginInfo rpbi = {VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO};
            rpbi.renderPass = fp.rp; rpbi.framebuffer = fb;
            rpbi.renderArea.extent = {ms, ms};
            vkCmdBeginRenderPass(cmd, &rpbi, VK_SUBPASS_CONTENTS_INLINE);
            VkViewport vpr = {0, 0, (float)ms, (float)ms, 0, 1};
            VkRect2D sc = {{0, 0}, {ms, ms}};
            vkCmdSetViewport(cmd, 0, 1, &vpr); vkCmdSetScissor(cmd, 0, 1, &sc);
            vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, fp.pipe);
            if (envSet_) {
                vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, fp.layout,
                                        0, 1, &envSet_, 0, nullptr);
            }
            Push pcv = {(int32_t)f, rough, envIsHdri_ ? 1.0f : 0.0f,
                        envUsesRoom() ? 1.0f : 0.0f};
            vkCmdPushConstants(cmd, fp.layout, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(Push), &pcv);
            vkCmdDraw(cmd, 3, 1, 0, 0);
            vkCmdEndRenderPass(cmd);
            vkEndCommandBuffer(cmd);
            VkSubmitInfo si = {VK_STRUCTURE_TYPE_SUBMIT_INFO}; si.commandBufferCount = 1; si.pCommandBuffers = &cmd;
            vkQueueSubmit(queue_, 1, &si, VK_NULL_HANDLE); vkQueueWaitIdle(queue_);
            vkFreeCommandBuffers(device_, cmdPool_, 1, &cmd);
            vkDestroyFramebuffer(device_, fb, nullptr);
            vkDestroyImageView(device_, faceView, nullptr);
        }
    }
    destroyFsPipe(device_, fp);
    return true;
}

bool ModelRenderer::createIbl() {
    VkSamplerCreateInfo sc = {VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO};
    sc.magFilter = VK_FILTER_LINEAR; sc.minFilter = VK_FILTER_LINEAR;
    sc.mipmapMode = VK_SAMPLER_MIPMAP_MODE_LINEAR;
    sc.addressModeU = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    sc.addressModeV = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    sc.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    sc.maxLod = VK_LOD_CLAMP_NONE; sc.borderColor = VK_BORDER_COLOR_FLOAT_OPAQUE_WHITE;
    if (vkCreateSampler(device_, &sc, nullptr, &iblCubeSampler_) != VK_SUCCESS) return false;
    VkSamplerCreateInfo sl = sc; sl.maxLod = 0.0f;
    if (vkCreateSampler(device_, &sl, nullptr, &iblLutSampler_) != VK_SUCCESS) return false;
    // Clamped so a refraction ray leaving the frame smears the edge rather than
    // wrapping the opposite side of the scene into the glass.
    if (vkCreateSampler(device_, &sc, nullptr, &transmissionSampler_) != VK_SUCCESS) return false;

    // The environment the cubes are baked FROM (set 0 of the generation passes).
    // Must exist before genCubeMap, which binds it.
    if (!createEnvDescriptor()) return false;

    // The split-sum BRDF LUT and the sheen directional-albedo LUT are both
    // "run one fullscreen pass into an R16G16 table once at startup", so they
    // share a baker rather than two near-identical 25-line blocks.
    auto bakeLut = [&](ModelImage& dst, uint32_t size,
                       const uint32_t* spv, size_t spvBytes) -> bool {
        dst = modelCreateImage2D(device_, physDevice_, size, size, VK_FORMAT_R16G16_SFLOAT,
            VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT);
        if (dst.image == VK_NULL_HANDLE) return false;
        FsPipe fp = makeFsPipe(device_, VK_FORMAT_R16G16_SFLOAT, spv, spvBytes, 0);
        VkFramebufferCreateInfo fbci = {VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO};
        fbci.renderPass = fp.rp; fbci.attachmentCount = 1; fbci.pAttachments = &dst.view;
        fbci.width = size; fbci.height = size; fbci.layers = 1;
        VkFramebuffer fb; vkCreateFramebuffer(device_, &fbci, nullptr, &fb);
        VkCommandBufferAllocateInfo cai = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
        cai.commandPool = cmdPool_; cai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY; cai.commandBufferCount = 1;
        VkCommandBuffer cmd; vkAllocateCommandBuffers(device_, &cai, &cmd);
        VkCommandBufferBeginInfo bi = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
        bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
        vkBeginCommandBuffer(cmd, &bi);
        VkRenderPassBeginInfo rpbi = {VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO};
        rpbi.renderPass = fp.rp; rpbi.framebuffer = fb; rpbi.renderArea.extent = {size, size};
        vkCmdBeginRenderPass(cmd, &rpbi, VK_SUBPASS_CONTENTS_INLINE);
        VkViewport vpr = {0, 0, (float)size, (float)size, 0, 1}; VkRect2D scs = {{0, 0}, {size, size}};
        vkCmdSetViewport(cmd, 0, 1, &vpr); vkCmdSetScissor(cmd, 0, 1, &scs);
        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, fp.pipe);
        vkCmdDraw(cmd, 3, 1, 0, 0);
        vkCmdEndRenderPass(cmd); vkEndCommandBuffer(cmd);
        VkSubmitInfo si = {VK_STRUCTURE_TYPE_SUBMIT_INFO}; si.commandBufferCount = 1; si.pCommandBuffers = &cmd;
        vkQueueSubmit(queue_, 1, &si, VK_NULL_HANDLE); vkQueueWaitIdle(queue_);
        vkFreeCommandBuffers(device_, cmdPool_, 1, &cmd);
        vkDestroyFramebuffer(device_, fb, nullptr);
        destroyFsPipe(device_, fp);
        return true;
    };
    if (!bakeLut(brdfLut_, 256, brdf_lut_frag_data, sizeof(brdf_lut_frag_data))) return false;
    // 64² is plenty: E is smooth in both N·V and roughness.
    if (!bakeLut(sheenLut_, 64, sheen_lut_frag_data, sizeof(sheen_lut_frag_data))) return false;

    if (!bakeIblCubes()) return false;

    // Descriptor set (set = 2).
    VkDescriptorPoolSize ps = {VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 5};
    VkDescriptorPoolCreateInfo dpci = {VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
    dpci.maxSets = 1; dpci.poolSizeCount = 1; dpci.pPoolSizes = &ps;
    if (vkCreateDescriptorPool(device_, &dpci, nullptr, &iblPool_) != VK_SUCCESS) return false;
    VkDescriptorSetAllocateInfo dsai = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    dsai.descriptorPool = iblPool_; dsai.descriptorSetCount = 1; dsai.pSetLayouts = &iblSetLayout_;
    if (vkAllocateDescriptorSets(device_, &dsai, &iblSet_) != VK_SUCCESS) return false;
    writeIblSet();
    std::printf("ModelRenderer: IBL ready (irradiance 32, prefilter 128x%u, BRDF LUT 256)\n", prefilterCube_.mips);
    return true;
}

// Set 2 is written from several places — first bake, environment change, and
// window resize (which recreates the transmission image). One function so the
// four bindings can never drift out of step.
void ModelRenderer::writeIblSet() {
    VkDescriptorImageInfo ii[5] = {
        {iblCubeSampler_,      irradianceCube_.view,    VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
        {iblCubeSampler_,      prefilterCube_.view,     VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
        {iblLutSampler_,       brdfLut_.view,           VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
        {transmissionSampler_, transmissionImage_.view, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
        {iblLutSampler_,       sheenLut_.view,          VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
    };
    VkWriteDescriptorSet w[5];
    uint32_t n = 0;
    for (uint32_t i = 0; i < 5; ++i) {
        if (ii[i].imageView == VK_NULL_HANDLE) continue;   // not created yet
        w[n] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        w[n].dstSet = iblSet_; w[n].dstBinding = i; w[n].descriptorCount = 1;
        w[n].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER; w[n].pImageInfo = &ii[i];
        ++n;
    }
    if (n) vkUpdateDescriptorSets(device_, n, w, 0, nullptr);
}

void ModelRenderer::destroyCubeMap(CubeMap& cube) {
    if (cube.view)   vkDestroyImageView(device_, cube.view, nullptr);
    if (cube.image)  vkDestroyImage(device_, cube.image, nullptr);
    if (cube.memory) vkFreeMemory(device_, cube.memory, nullptr);
    cube = {};
}

// (Re)bake the two IBL cubes from whatever environment is currently bound.
// Called once from createIbl(), again on every setEnvironment(), and again on
// any lighting-mode change that swaps the analytic source (setLightingMode →
// envUsesRoom: sky.glsl ↔ room.glsl). Blocking —
// genCubeMap submits and waits per face/mip — so this is a load-time operation,
// never a per-frame one.
bool ModelRenderer::bakeIblCubes() {
    // A rebake must not run while the previous cubes are still referenced by
    // in-flight work, and it destroys images the descriptor set points at.
    vkQueueWaitIdle(queue_);
    destroyCubeMap(irradianceCube_);
    destroyCubeMap(prefilterCube_);

    if (!genCubeMap(irradianceCube_, 32, 1, irradiance_frag_data, sizeof(irradiance_frag_data), false)) return false;
    if (!genCubeMap(prefilterCube_, 128, 5, prefilter_frag_data, sizeof(prefilter_frag_data), true)) return false;

    // Repoint set 2 at the new images (no-op on the first bake, when the set
    // hasn't been allocated yet — createIbl writes it right after).
    if (iblSet_ != VK_NULL_HANDLE) {
        VkDescriptorImageInfo ii[2] = {
            {iblCubeSampler_, irradianceCube_.view, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
            {iblCubeSampler_, prefilterCube_.view,  VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL},
        };
        VkWriteDescriptorSet w[2];
        for (uint32_t i = 0; i < 2; ++i) {
            w[i] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
            w[i].dstSet = iblSet_; w[i].dstBinding = i; w[i].descriptorCount = 1;
            w[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER; w[i].pImageInfo = &ii[i];
        }
        vkUpdateDescriptorSets(device_, 2, w, 0, nullptr);
    }
    return true;
}

// Set 0 of the IBL generation passes: the equirectangular environment texture.
// Always bound to something valid — envDummyTex_ when no HDRI is loaded, since
// a descriptor must reference a live image even on the analytic-sky branch that
// never samples it.
bool ModelRenderer::createEnvDescriptor() {
    // Equirect wraps in longitude and clamps at the poles.
    VkSamplerCreateInfo sci = {VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO};
    sci.magFilter = VK_FILTER_LINEAR; sci.minFilter = VK_FILTER_LINEAR;
    sci.mipmapMode = VK_SAMPLER_MIPMAP_MODE_LINEAR;
    sci.addressModeU = VK_SAMPLER_ADDRESS_MODE_REPEAT;
    sci.addressModeV = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    sci.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
    sci.maxLod = 0.0f; sci.borderColor = VK_BORDER_COLOR_FLOAT_OPAQUE_WHITE;
    if (vkCreateSampler(device_, &sci, nullptr, &envSampler_) != VK_SUCCESS) return false;

    VkDescriptorSetLayoutBinding b = {0, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1,
                                      VK_SHADER_STAGE_FRAGMENT_BIT, nullptr};
    VkDescriptorSetLayoutCreateInfo lci = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
    lci.bindingCount = 1; lci.pBindings = &b;
    if (vkCreateDescriptorSetLayout(device_, &lci, nullptr, &envSetLayout_) != VK_SUCCESS) return false;

    VkDescriptorPoolSize ps = {VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1};
    VkDescriptorPoolCreateInfo dpci = {VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
    dpci.maxSets = 1; dpci.poolSizeCount = 1; dpci.pPoolSizes = &ps;
    if (vkCreateDescriptorPool(device_, &dpci, nullptr, &envPool_) != VK_SUCCESS) return false;
    VkDescriptorSetAllocateInfo dsai = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    dsai.descriptorPool = envPool_; dsai.descriptorSetCount = 1; dsai.pSetLayouts = &envSetLayout_;
    if (vkAllocateDescriptorSets(device_, &dsai, &envSet_) != VK_SUCCESS) return false;

    ModelTexture dummy; dummy.width = 1; dummy.height = 1; dummy.rgba = {0, 0, 0, 255};
    envDummyTex_ = uploadTexture(dummy);
    if (envDummyTex_.view == VK_NULL_HANDLE) return false;
    bindEnvEquirect(envDummyTex_.view);
    return true;
}

void ModelRenderer::bindEnvEquirect(VkImageView v) {
    VkDescriptorImageInfo ii = {envSampler_, v, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL};
    VkWriteDescriptorSet w = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
    w.dstSet = envSet_; w.dstBinding = 0; w.descriptorCount = 1;
    w.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER; w.pImageInfo = &ii;
    vkUpdateDescriptorSets(device_, 1, &w, 0, nullptr);
}

namespace {
// float32 → IEEE half. R16G16B16A16_SFLOAT is the widest float format with
// guaranteed linear-filter support, so the HDRI is stored as half; R32 float
// images are NOT required to be filterable. Values above the half max are
// clamped — the generation passes clamp far lower anyway (ENV_RADIANCE_CLAMP).
uint16_t floatToHalf(float f) {
    if (!(f > 0.0f)) return 0;                 // negatives + NaN → 0 (radiance is non-negative)
    if (f >= 65504.0f) return 0x7BFF;          // half max
    if (f < 6.103515625e-05f) return 0;        // flush denormals to zero
    uint32_t b; std::memcpy(&b, &f, 4);
    return (uint16_t)(((b >> 16) & 0x8000) | (((b >> 13) - (112 << 10)) & 0x7FFF));
}
}  // namespace

bool ModelRenderer::setEnvironment(const char* hdriPath) {
    if (!initialized_) return false;

    // Empty/null → revert to the analytic environment the lighting mode implies.
    if (hdriPath == nullptr || hdriPath[0] == '\0') {
        if (!envIsHdri_) return true;
        vkQueueWaitIdle(queue_);
        bindEnvEquirect(envDummyTex_.view);
        modelDestroyImage(device_, envEquirect_);
        envIsHdri_ = false;
        // Dropping an HDRI while lighting=room must land on the ROOM, not on
        // the sky — envUsesRoom() is the one place that decision is made.
        envName_ = envUsesRoom() ? "analytic room" : "analytic sky";
        std::printf("ModelRenderer: environment → %s\n", envName_.c_str());
        return bakeIblCubes();
    }

    int w = 0, h = 0, comp = 0;
    float* px = stbi_loadf(hdriPath, &w, &h, &comp, 4);   // force RGBA
    if (!px) {
        std::printf("ModelRenderer: HDRI load failed (%s): %s — keeping %s\n", hdriPath,
                    stbi_failure_reason() ? stbi_failure_reason() : "unknown", envName_.c_str());
        return false;
    }

    std::vector<uint16_t> half((size_t)w * h * 4);
    for (size_t i = 0; i < half.size(); ++i) half[i] = floatToHalf(px[i]);
    stbi_image_free(px);

    ModelImage img = modelCreateImage2D(device_, physDevice_, (uint32_t)w, (uint32_t)h,
                                        VK_FORMAT_R16G16B16A16_SFLOAT,
                                        VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT);
    if (img.image == VK_NULL_HANDLE) return false;

    const VkDeviceSize bytes = (VkDeviceSize)half.size() * sizeof(uint16_t);
    ModelBuffer staging = modelCreateBuffer(device_, physDevice_, bytes,
        VK_BUFFER_USAGE_TRANSFER_SRC_BIT,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    void* mapped = nullptr;
    vkMapMemory(device_, staging.memory, 0, bytes, 0, &mapped);
    std::memcpy(mapped, half.data(), (size_t)bytes);
    vkUnmapMemory(device_, staging.memory);

    VkCommandBufferAllocateInfo cai = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
    cai.commandPool = cmdPool_; cai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY; cai.commandBufferCount = 1;
    VkCommandBuffer cmd; vkAllocateCommandBuffers(device_, &cai, &cmd);
    VkCommandBufferBeginInfo bi = {VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(cmd, &bi);
    auto barrier = [&](VkImageLayout oldL, VkImageLayout newL, VkAccessFlags srcA, VkAccessFlags dstA,
                       VkPipelineStageFlags srcS, VkPipelineStageFlags dstS) {
        VkImageMemoryBarrier b = {VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
        b.oldLayout = oldL; b.newLayout = newL;
        b.srcAccessMask = srcA; b.dstAccessMask = dstA;
        b.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED; b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        b.image = img.image;
        b.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
        vkCmdPipelineBarrier(cmd, srcS, dstS, 0, 0, nullptr, 0, nullptr, 1, &b);
    };
    barrier(VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
            0, VK_ACCESS_TRANSFER_WRITE_BIT,
            VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT);
    VkBufferImageCopy region = {};
    region.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    region.imageExtent = {(uint32_t)w, (uint32_t)h, 1};
    vkCmdCopyBufferToImage(cmd, staging.buffer, img.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);
    barrier(VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
            VK_ACCESS_TRANSFER_WRITE_BIT, VK_ACCESS_SHADER_READ_BIT,
            VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT);
    vkEndCommandBuffer(cmd);
    VkSubmitInfo si = {VK_STRUCTURE_TYPE_SUBMIT_INFO}; si.commandBufferCount = 1; si.pCommandBuffers = &cmd;
    vkQueueSubmit(queue_, 1, &si, VK_NULL_HANDLE);
    vkQueueWaitIdle(queue_);
    vkFreeCommandBuffers(device_, cmdPool_, 1, &cmd);
    modelDestroyBuffer(device_, staging);

    // Swap in the new environment, then rebake. Only now is the old image dead.
    modelDestroyImage(device_, envEquirect_);
    envEquirect_ = img;
    envIsHdri_ = true;
    envName_ = std::filesystem::path(hdriPath).filename().string();
    bindEnvEquirect(envEquirect_.view);
    std::printf("ModelRenderer: environment → %s (%dx%d HDRI); analytic key light off\n",
                envName_.c_str(), w, h);
    return bakeIblCubes();
}

