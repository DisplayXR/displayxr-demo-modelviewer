// ===========================================================================
// Studio rig - the storefront page's lighting, reproduced.
//
// NOTE (room): the page's DEFAULT has since moved to `room` - three.js
// RoomEnvironment baked to a PMREM, no punctual lights at all - which this
// viewer reproduces in shaders/room.glsl rather than here, because it is an
// ENVIRONMENT and belongs in the IBL bake. The studio rig below is still what
// a page lights with when it asks for env=studio, so it stays exactly as it
// was. See ModelRenderer::LightingMode.
//
// The DisplayXR storefront's inline-3D tile lights every model with three.js's
// addStudioLights (displayxr-shop-pvt, src/vendor/inline3d/inline3d-model.js):
// three DirectionalLights plus a HemisphereLight, physically-correct
// intensities, NO environment map, and a WebGLRenderer left at the default
// NoToneMapping. When a page hands a model to this viewer over displayxr-view:
// the two end up side by side on one desktop, so anything that does not match
// reads as a bug in the viewer. Metal is where it shows: three sharp lights on
// an otherwise unlit body read as metal, while this viewer's smooth analytic
// sky gives the same body a uniform grey reflection that reads as matte.
//
// three.js and this renderer already share a world frame - +Y up, camera down
// -Z so +Z is toward the viewer - and a three.js DirectionalLight points from
// its `position` at the origin. So a light's `position`, normalised, IS the
// shader's world direction TO the light, with no change of basis. Verified by
// eye on an atlas capture, not assumed.
namespace {

constexpr float kStudioKeyDir[3]  = { 1.0f,  1.4f,  1.6f};   // upper front right
constexpr float kStudioKeyI       = 2.2f;
constexpr float kStudioFillDir[3] = {-1.4f,  0.4f,  0.8f};   // front left, low
constexpr float kStudioFillI      = 0.7f;
constexpr float kStudioRimDir[3]  = {-0.4f,  0.8f, -1.6f};   // behind, upper left
constexpr float kStudioRimI       = 1.0f;
constexpr float kStudioHemiI      = 0.6f;

// HemisphereLight(sky 0xffffff, ground 0x444444). three.js r152+ has
// ColorManagement on by default, so a hex colour is DECODED from sRGB into the
// linear working space before it is ever used: the ground is 0.0578 linear, not
// 0x44/255 = 0.267. Getting this wrong lifts every downward-facing surface by
// ~4.6x, which on a bottle is the whole lower half.
constexpr float kStudioHemiSky[3]    = {1.0f, 1.0f, 1.0f};
constexpr float kStudioHemiGround[3] = {0.057805f, 0.057805f, 0.057805f};

// How much of the analytic-sky IBL survives under Studio.
//
// The faithful number is 0: the page has no environment map at all, so its
// metal is lit by three lights and nothing else. It is 0.15 instead for one
// reason specific to this display - a metal with no environment goes pure black
// everywhere the three lights miss, and a black region is the one thing a
// lightfield panel has NO parallax detail to show. A body that is black in
// every view carries no depth cue at all, so the object reads as a flat cut-out
// floating in front of the desktop. 0.15 leaves the direct highlights dominant
// by close to an order of magnitude (measured on WaterBottle.glb; see the #113
// PR comment) while keeping the body's form readable in 3D.
constexpr float kStudioIblScale = 0.15f;

void normalizeInto(float out[4], const float dir[3], float intensity) {
    const float n = std::sqrt(dir[0]*dir[0] + dir[1]*dir[1] + dir[2]*dir[2]);
    const float inv = (n > 1e-6f) ? (1.0f / n) : 0.0f;
    out[0] = dir[0] * inv; out[1] = dir[1] * inv; out[2] = dir[2] * inv;
    out[3] = intensity;
}

}  // namespace

void ModelRenderer::setLightingMode(LightingMode m) {
    const bool wasRoom = envUsesRoom();
    lightingMode_ = m;
    // Room swaps the environment the IBL cubes are BAKED from, which nothing
    // else about a mode does — Sky/Studio/None all read the same sky bake and
    // differ only in uniforms. So this one transition needs a rebake.
    //
    // Rebake on the transition rather than baking both sets at init: a second
    // pair of cubes is ~1.6 MB of VRAM plus a second descriptor to switch, and
    // it would pay the room's bake cost on EVERY launch — including the common
    // one that never presses L. The rebake is the same handful of blocking
    // fullscreen passes setEnvironment already runs (~100 ms, measured 0.09 s
    // for room), on an explicit user action or at startup, never per frame.
    // initialized_ gates the startup call: main() sets the launch mode before
    // the model loads but AFTER init, and createIbl() bakes for itself.
    if (envUsesRoom() != wasRoom) {
        // The HUD's environment line is what makes a capture self-documenting,
        // so it has to name the source that was actually integrated — "analytic
        // sky" under a room bake would be a lie in every reference image.
        envName_ = envUsesRoom() ? "analytic room" : "analytic sky";
    }
    if (initialized_ && envUsesRoom() != wasRoom) {
        if (!bakeIblCubes()) {
            std::printf("ModelRenderer: IBL rebake for lighting=%s FAILED — "
                        "the previous environment is gone; expect a black ambient\n",
                        lightingModeName());
        }
    }
    // The grading is PART of the mode. The page runs three.js at unit exposure
    // with NoToneMapping, so Studio has to as well - a filmic knee alone would
    // pull every highlight the rig exists to produce back under 1.0 and undo
    // the comparison. Sky keeps the #70 phase-0 pairing (PBR Neutral needs the
    // +1 EV to reach its knee at all). [ / ] and G still override afterwards;
    // this only sets the mode's starting point.
    // Room grades like Studio and for the same reason: it is the SAME page,
    // whose WebGLRenderer is at its NoToneMapping / unit-exposure default. The
    // room's radiances are physical (a 43-unit panel at 17 m, not a hand-picked
    // "1.0"), so the match is only a match at 0 EV with no curve.
    if (m == LightingMode::Studio || m == LightingMode::Room) {
        exposureEV_ = 0.0f;
        toneCurve_  = ToneCurve::Clamp;
    } else {
        exposureEV_ = 1.0f;
        toneCurve_  = ToneCurve::PbrNeutral;
    }
    std::printf("ModelRenderer: lighting = %s (exposure %+.2f EV, tone %s)\n",
                lightingModeName(), exposureEV_, toneCurveName());
}

const char* ModelRenderer::lightingModeName() const {
    switch (lightingMode_) {
        case LightingMode::Studio: return "studio";
        case LightingMode::Room:   return "room";
        case LightingMode::NoLights:   return "none";
        default:                   return "sky";
    }
}

void ModelRenderer::cycleLightingMode() {
    setLightingMode(lightingMode_ == LightingMode::Sky    ? LightingMode::Studio
                  : lightingMode_ == LightingMode::Studio ? LightingMode::Room
                  : lightingMode_ == LightingMode::Room   ? LightingMode::NoLights
                                                          : LightingMode::Sky);
}

bool ModelRenderer::parseLightingMode(const std::string& env, LightingMode& out) {
    if (env == "studio") { out = LightingMode::Studio; return true; }
    if (env == "sky")    { out = LightingMode::Sky;    return true; }
    if (env == "room")   { out = LightingMode::Room;   return true; }
    if (env == "none")   { out = LightingMode::NoLights;   return true; }
    return false;
}

VkDescriptorSet ModelRenderer::makeMaterialSet(const VkImageView views[MTEX_COUNT]) {
    VkDescriptorSetAllocateInfo ai = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    ai.descriptorPool = matPool_;
    ai.descriptorSetCount = 1;
    ai.pSetLayouts = &matSetLayout_;
    VkDescriptorSet set = VK_NULL_HANDLE;
    if (vkAllocateDescriptorSets(device_, &ai, &set) != VK_SUCCESS) return VK_NULL_HANDLE;

    VkDescriptorImageInfo infos[MTEX_COUNT];
    VkWriteDescriptorSet writes[MTEX_COUNT];
    for (uint32_t i = 0; i < MTEX_COUNT; ++i) {
        infos[i] = {sampler_, views[i], VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL};
        writes[i] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        writes[i].dstSet = set;
        writes[i].dstBinding = i;
        writes[i].descriptorCount = 1;
        writes[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        writes[i].pImageInfo = &infos[i];
    }
    vkUpdateDescriptorSets(device_, MTEX_COUNT, writes, 0, nullptr);
    return set;
}

bool ModelRenderer::finalizeModel(ModelData& md) {
    cleanupModel();

    // Morph models need a CPU-writable vertex buffer (re-blended each frame);
    // everything else keeps the device-local staged upload.
    hasMorph_ = !md.morphs.empty();
    const VkDeviceSize vbSize = md.vertices.size() * sizeof(ModelVertex);
    vertexBuffer_ = modelCreateBuffer(device_, physDevice_, vbSize,
        VK_BUFFER_USAGE_VERTEX_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT,
        hasMorph_ ? (VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT)
                  : VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    indexBuffer_ = modelCreateBuffer(device_, physDevice_,
        md.indices.size() * sizeof(uint32_t),
        VK_BUFFER_USAGE_INDEX_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT,
        VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (vertexBuffer_.buffer == VK_NULL_HANDLE || indexBuffer_.buffer == VK_NULL_HANDLE) return false;
    if (hasMorph_) {
        // Keep the base verts for re-blending; seed the buffer with them.
        morphBase_ = md.vertices;
        void* mapped = nullptr;
        vkMapMemory(device_, vertexBuffer_.memory, 0, vbSize, 0, &mapped);
        std::memcpy(mapped, md.vertices.data(), (size_t)vbSize);
        vkUnmapMemory(device_, vertexBuffer_.memory);
    } else {
        modelUploadBuffer(device_, physDevice_, queue_, cmdPool_, vertexBuffer_,
                          md.vertices.data(), vertexBuffer_.size);
    }
    modelUploadBuffer(device_, physDevice_, queue_, cmdPool_, indexBuffer_,
                      md.indices.data(), indexBuffer_.size);

    // Upload textures (parallel to md.textures; empty entries stay null).
    modelTextures_.resize(md.textures.size());
    for (size_t i = 0; i < md.textures.size(); ++i)
        if (!md.textures[i].rgba.empty())
            modelTextures_[i] = uploadTexture(md.textures[i]);

    materials_ = std::move(md.materials);
    hasTransmissive_ = false;
    for (const ModelMaterial& m : materials_)
        if (m.transmissionFactor > 0.0f) { hasTransmissive_ = true; break; }
    if (!uploadMaterialExtensions(materials_)) return false;
    primitives_ = std::move(md.primitives);

    // Animation graph (Phase 1). Auto-play the first clip; no clips → static
    // fast-path (activeAnim_ stays -1 and updateAnimation is a no-op).
    nodes_ = std::move(md.nodes);
    animations_ = std::move(md.animations);
    rootNodes_ = std::move(md.rootNodes);
    morphs_ = std::move(md.morphs);
    bindNodes_ = nodes_;                  // bind-pose snapshot for clean clip switches
    nodeWorld_.assign(nodes_.size() * 16, 0.0f);
    activeAnim_ = animations_.empty() ? -1 : 0;
    animTime_ = 0.0f;
    paused_ = false;

    // ── Skinning: joint-matrix SSBO (set = 3) ────────────────────────────────
    // Sized to all skins' joints concatenated; ≥1 matrix so static models still
    // bind a valid set 3. Host-visible: updateAnimation memcpy's it each frame.
    // Initialized to identity — the static fast-path then leaves it untouched.
    skins_ = std::move(md.skins);
    jointCount_ = md.totalJoints > 0 ? md.totalJoints : 1;
    jointBuffer_ = modelCreateBuffer(device_, physDevice_,
        (VkDeviceSize)jointCount_ * 16 * sizeof(float),
        VK_BUFFER_USAGE_STORAGE_BUFFER_BIT,
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    if (jointBuffer_.buffer == VK_NULL_HANDLE) return false;
    {
        void* mapped = nullptr;
        vkMapMemory(device_, jointBuffer_.memory, 0, jointBuffer_.size, 0, &mapped);
        const glm::mat4 ident(1.0f);
        for (uint32_t i = 0; i < jointCount_; ++i)
            std::memcpy((char*)mapped + i * 16 * sizeof(float), glm::value_ptr(ident), 16 * sizeof(float));
        vkUnmapMemory(device_, jointBuffer_.memory);
    }
    {
        VkDescriptorPoolSize jps = {VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1};
        VkDescriptorPoolCreateInfo jdpci = {VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
        jdpci.maxSets = 1;
        jdpci.poolSizeCount = 1;
        jdpci.pPoolSizes = &jps;
        if (vkCreateDescriptorPool(device_, &jdpci, nullptr, &jointPool_) != VK_SUCCESS) return false;
        VkDescriptorSetAllocateInfo jdsai = {VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
        jdsai.descriptorPool = jointPool_;
        jdsai.descriptorSetCount = 1;
        jdsai.pSetLayouts = &jointSetLayout_;
        if (vkAllocateDescriptorSets(device_, &jdsai, &jointSet_) != VK_SUCCESS) return false;
        VkDescriptorBufferInfo jdbi = {jointBuffer_.buffer, 0, jointBuffer_.size};
        VkWriteDescriptorSet jw = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        jw.dstSet = jointSet_;
        jw.dstBinding = 0;
        jw.descriptorCount = 1;
        jw.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        jw.pBufferInfo = &jdbi;
        vkUpdateDescriptorSets(device_, 1, &jw, 0, nullptr);
    }

    std::memcpy(bboxMin_, md.bboxMin, sizeof(bboxMin_));
    std::memcpy(bboxMax_, md.bboxMax, sizeof(bboxMax_));
    hasBBox_ = md.hasBBox;
    numPrimitives_ = md.primitiveCount;

    // For animated models, replace the bind-pose AABB with the swept animated
    // bounds (correct height/center for the auto-fit). Needs primitives_/nodes_/
    // animations_/skins_ (set above) plus the still-intact CPU verts + indices.
    recomputeAnimatedBounds(md.vertices, md.indices);

    // Apply the rest-pose morph once so a model with nonzero default weights and
    // no clip still shows its morphed shape (animated models re-blend per frame).
    blendMorphs();

    // Per-material descriptor sets (set = 1) + a default for material == -1.
    const uint32_t nSets = (uint32_t)materials_.size() + 1;
    VkDescriptorPoolSize ps = {VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, nSets * MTEX_COUNT};
    VkDescriptorPoolCreateInfo dpci = {VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
    dpci.maxSets = nSets;
    dpci.poolSizeCount = 1;
    dpci.pPoolSizes = &ps;
    if (vkCreateDescriptorPool(device_, &dpci, nullptr, &matPool_) != VK_SUCCESS) return false;

    auto viewOr = [&](int idx, VkImageView def) -> VkImageView {
        if (idx >= 0 && idx < (int)modelTextures_.size() && modelTextures_[idx].view != VK_NULL_HANDLE)
            return modelTextures_[idx].view;
        return def;
    };
    materialSets_.reserve(materials_.size());
    for (const auto& m : materials_) {
        // White is the correct absent-texture default for every one of these:
        // each sampled value MULTIPLIES its factor, so 1.0 is the identity.
        const VkImageView v[MTEX_COUNT] = {
            viewOr(m.baseColorTex,          whiteTex_.view),
            viewOr(m.metallicRoughnessTex,  whiteTex_.view),
            viewOr(m.normalTex,             flatNormalTex_.view),
            viewOr(m.occlusionTex,          whiteTex_.view),
            viewOr(m.emissiveTex,           whiteTex_.view),
            viewOr(m.clearcoatTex,          whiteTex_.view),
            viewOr(m.clearcoatRoughnessTex, whiteTex_.view),
            viewOr(m.sheenColorTex,         whiteTex_.view),
            viewOr(m.sheenRoughnessTex,     whiteTex_.view),
            viewOr(m.specularTex,           whiteTex_.view),
            viewOr(m.specularColorTex,      whiteTex_.view),
            viewOr(m.transmissionTex,       whiteTex_.view),
            viewOr(m.thicknessTex,          whiteTex_.view),
            viewOr(m.scatterStrengthTex,    whiteTex_.view),
            viewOr(m.multiscatterColorTex,  whiteTex_.view),
            viewOr(m.coatColorTex,          whiteTex_.view),
            viewOr(m.coatAnisotropyTex,     coatAnisoDefaultTex_.view),
            viewOr(m.diffuseRoughnessTex,   whiteTex_.view),
            viewOr(m.fuzzTex,               whiteTex_.view),
            viewOr(m.coatNormalTex,         flatNormalTex_.view),
        };
        materialSets_.push_back(makeMaterialSet(v));
    }
    VkImageView dflt[MTEX_COUNT];
    for (uint32_t i = 0; i < MTEX_COUNT; ++i) dflt[i] = whiteTex_.view;
    dflt[MTEX_NORMAL] = flatNormalTex_.view;
    dflt[MTEX_COAT_ANISOTROPY] = coatAnisoDefaultTex_.view;
    dflt[MTEX_COAT_NORMAL] = flatNormalTex_.view;
    defaultMatSet_ = makeMaterialSet(dflt);

    modelLoaded_ = true;
    return true;
}

// Every platform's file-open / drag-drop path funnels here, so this is also
// where an .hdr is recognised: dropping an environment map on the viewer swaps
// the lighting rather than failing as an unloadable mesh. The model on screen is
// untouched — which is the point, since comparing the same asset under a known
// environment is what makes a material comparison meaningful (issue #70).
bool ModelRenderer::loadModel(const char* gltfPath) {
    if (!initialized_ || !gltfPath) return false;
    {
        std::string ext = std::filesystem::path(gltfPath).extension().string();
        std::transform(ext.begin(), ext.end(), ext.begin(),
                       [](unsigned char c) { return (char)std::tolower(c); });
        if (ext == ".hdr") return setEnvironment(gltfPath);
    }
    ModelData md;
    if (!model_loader_load(gltfPath, md)) return false;
    if (!finalizeModel(md)) return false;
    loadedModelPath_ = gltfPath;
    unsupportedExtensions_ = md.unsupportedExtensions;
    return true;
}

std::string ModelRenderer::unsupportedExtensionsSummary(size_t maxNamed) const {
    if (unsupportedExtensions_.empty()) return std::string();
    // Drop the vendor prefix — "KHR_materials_clearcoat" is mostly boilerplate
    // and the HUD has one line to spend.
    auto shortName = [](const std::string& s) {
        static const std::string kPrefix = "KHR_materials_";
        return s.rfind(kPrefix, 0) == 0 ? s.substr(kPrefix.size()) : s;
    };
    const size_t n = unsupportedExtensions_.size();
    std::string out;
    for (size_t i = 0; i < n && i < maxNamed; ++i) {
        if (i) out += ", ";
        out += shortName(unsupportedExtensions_[i]);
    }
    if (n > maxNamed) out += ", +" + std::to_string(n - maxNamed) + " more";
    return out;
}

