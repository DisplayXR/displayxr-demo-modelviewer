void ModelRenderer::updateUniforms(const float viewMatrix[16], const float projMatrix[16],
                                   float clipFar) {
    // W7 (#396): consume a plain clean +Y-up-world view matrix (the render-ready
    // XR_DXR_view_rig XrView pose). Vulkan Y-down is handled at the RASTER stage
    // via a negative-height viewport in renderEye — NOT by reflecting the view
    // matrix. A view reflection renders correctly but flips rotational handedness
    // (inverting mouse pitch); the viewport flip does not, and keeps the off-axis
    // projection in its native +Y-up frame. -R^T·t below recovers the true world
    // camera for lighting/skybox. (vmFlipped kept as the name downstream; it is
    // now the un-reflected view.)
    float vmFlipped[16];
    std::memcpy(vmFlipped, viewMatrix, sizeof(vmFlipped));

    UniformBlock ub{};
    mat4Mul(projMatrix, vmFlipped, ub.viewProj);
    // inverse(viewProj) for the skybox per-pixel ray reconstruction.
    glm::mat4 ivp = glm::inverse(glm::make_mat4(ub.viewProj));
    std::memcpy(ub.invViewProj, glm::value_ptr(ivp), 16 * sizeof(float));

    // View matrix with the Z row negated → positive Z = forward (matches
    // gs_renderer / the eye_display.z forward distance), used by the shader's
    // foreground clip. Column-major Z-row indices: 2, 6, 10, 14.
    std::memcpy(ub.view, vmFlipped, sizeof(ub.view));
    ub.view[2]  = -ub.view[2];
    ub.view[6]  = -ub.view[6];
    ub.view[10] = -ub.view[10];
    ub.view[14] = -ub.view[14];

    // Camera world position = -R^T * t from the flipped view matrix.
    float tx = vmFlipped[12], ty = vmFlipped[13], tz = vmFlipped[14];
    ub.cameraPos[0] = -(vmFlipped[0] * tx + vmFlipped[1] * ty + vmFlipped[2] * tz);
    ub.cameraPos[1] = -(vmFlipped[4] * tx + vmFlipped[5] * ty + vmFlipped[6] * tz);
    ub.cameraPos[2] = -(vmFlipped[8] * tx + vmFlipped[9] * ty + vmFlipped[10] * tz);
    // .w = shader gamma-encode flag: encode linear→sRGB at output for a UNORM
    // swapchain (the DisplayXR compositor decodes it for presentation); skip for
    // an sRGB swapchain, whose blit already encodes. Repurposes an unused slot.
    ub.cameraPos[3] = swapchainIsSrgb_ ? 0.0f : 1.0f;

    const bool studio = (lightingMode_ == LightingMode::Studio);

    // Key light (world space), normalized. Studio takes the page's key
    // direction; Sky and None keep the direction the analytic sky bakes its sun
    // at (sky.glsl uses the same vector, so lit and reflected highlights agree).
    float lx = studio ? kStudioKeyDir[0] : 0.4f;
    float ly = studio ? kStudioKeyDir[1] : 0.8f;
    float lz = studio ? kStudioKeyDir[2] : 0.5f;
    float ln = std::sqrt(lx * lx + ly * ly + lz * lz);
    ub.lightDir[0] = lx / ln; ub.lightDir[1] = ly / ln; ub.lightDir[2] = lz / ln;
    ub.lightDir[3] = (clipFar > 0.0f) ? clipFar : 0.0f;  // foreground clip (view-space)

    // Grading (issue #70 phase 0). .z gates the analytic key light off under an
    // HDRI, which already contains its own sun - see pbr.frag. None gates it off
    // outright (that mode IS "ambient only"). Studio ignores .z entirely: its
    // key scale comes from studio.y, so an HDRI cannot silently unlight it.
    ub.tone[0] = std::pow(2.0f, exposureEV_);
    ub.tone[1] = (float)(int)toneCurve_;
    // Room is ambient-only by construction: the page has NO punctual light in
    // room mode, every photon comes from the baked environment. So it gates the
    // key light off exactly the way None does - leaving it on would add a sun
    // the page does not have, on top of an environment that already lights the
    // model.
    ub.tone[2] = (lightingMode_ == LightingMode::NoLights
                  || lightingMode_ == LightingMode::Room || envIsHdri_) ? 0.0f : 1.0f;
    ub.tone[3] = transmissionProbe_ ? 1.0f : 0.0f;
    ub.viewport[0] = (width_  > 0) ? (float)vpWidth_  / (float)width_  : 1.0f;
    ub.viewport[1] = (height_ > 0) ? (float)vpHeight_ / (float)height_ : 1.0f;

    // Studio rig. Written unconditionally (zero-cost: the shader reads them
    // only when studio.x is 1) so a mode switch is one uniform away and never
    // leaves a stale direction behind.
    ub.studio[0] = studio ? 1.0f : 0.0f;
    ub.studio[1] = kStudioKeyI;
    ub.studio[2] = kStudioHemiI;
    ub.studio[3] = kStudioIblScale;
    normalizeInto(ub.studioFill, kStudioFillDir, kStudioFillI);
    normalizeInto(ub.studioRim,  kStudioRimDir,  kStudioRimI);
    ub.hemiSky[0]    = kStudioHemiSky[0];
    ub.hemiSky[1]    = kStudioHemiSky[1];
    ub.hemiSky[2]    = kStudioHemiSky[2];
    ub.hemiGround[0] = kStudioHemiGround[0];
    ub.hemiGround[1] = kStudioHemiGround[1];
    ub.hemiGround[2] = kStudioHemiGround[2];
    // DXR_MODELVIEWER_KULLA_CONTY=1 switches the scatter lobe to the spec's
    // multi->single scatter albedo remap, so the two can be MEASURED against the
    // conformance references rather than argued about. See pbr.frag.
    static const bool kullaConty = [] {
        const char* e = std::getenv("DXR_MODELVIEWER_KULLA_CONTY");
        return e && *e && *e != '0';
    }();
    ub.viewport[2] = kullaConty ? 1.0f : 0.0f;
    // DXR_MODELVIEWER_COAT_SPEC_HEMI=1 restores KHR_materials_coat's LITERAL
    // hemisphere-averaged reflectance for coat darkening (F_0 + 0.5*F_90), which
    // we otherwise replace with the true cosine-weighted average. Kept switchable
    // for the same reason the Kulla-Conty remap above is: the deviation is a
    // claim about the spec being wrong, and a claim like that should stay
    // measurable rather than becoming folklore. See pbr.frag (#90).
    static const bool coatSpecHemi = [] {
        const char* e = std::getenv("DXR_MODELVIEWER_COAT_SPEC_HEMI");
        return e && *e && *e != '0';
    }();
    ub.viewport[3] = coatSpecHemi ? 1.0f : 0.0f;

    void* mapped = nullptr;
    vkMapMemory(device_, uniformBuffer_.memory, 0, sizeof(UniformBlock), 0, &mapped);
    std::memcpy(mapped, &ub, sizeof(UniformBlock));
    vkUnmapMemory(device_, uniformBuffer_.memory);
}

